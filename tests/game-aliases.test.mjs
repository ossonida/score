import test from 'node:test';import assert from 'node:assert/strict';
const memory=()=>{const m=new Map();return {getItem:k=>m.has(k)?m.get(k):null,setItem:(k,v)=>m.set(k,String(v)),removeItem:k=>m.delete(k)};};
globalThis.localStorage=memory();
const {readGameAliases,rememberGameAlias,withAliasMatches,aliasSearchName,hasHangul}=await import('../game-aliases.js');
test('remembered Korean aliases are kept per account, deduplicated and newest first',()=>{globalThis.localStorage=memory();
 assert.equal(rememberGameAlias('a',{name:'Container',bggId:'17223'},'컨테'),true);
 assert.equal(rememberGameAlias('a',{name:'Container',bggId:'17223'},' 컨테 '),false);
 assert.equal(rememberGameAlias('a',{name:'Container',bggId:'17223'},'컨테이너'),true);
 assert.deepEqual(readGameAliases('a'),[{id:'17223',name:'Container',aliases:['컨테이너','컨테']}]);
 assert.deepEqual(readGameAliases('b'),[]);
 assert.equal(rememberGameAlias('a',{name:'Container',bggId:'17223'},'Container'),false);
 assert.equal(rememberGameAlias('a',{name:'Typed only',bggId:''},'아무게임'),false);
});
test('aliases add search results and translate an exact alias for BGG search',()=>{globalThis.localStorage=memory();
 rememberGameAlias('a',{name:'Container',bggId:'17223'},'컨테이너');const entries=readGameAliases('a');
 assert.deepEqual(withAliasMatches([],'컨테',entries),[{id:'17223',name:'Container',source:'내 별칭'}]);
 assert.deepEqual(withAliasMatches([{id:'17223',name:'Container',source:'BGG'}],'컨테이너',entries).length,1);
 assert.deepEqual(withAliasMatches([{name:'홀덤',scoreGame:true}],'컨테',entries),[{name:'홀덤',scoreGame:true}]);
 assert.equal(aliasSearchName('컨테이너',entries),'Container');assert.equal(aliasSearchName('컨테',entries),'컨테');
 assert.equal(hasHangul('컨테'),true);assert.equal(hasHangul('Container'),false);
});
